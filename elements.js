function periodicPos(n) {
  if (n === 1) return [1, 1];
  if (n === 2) return [1, 18];
  if (n <= 4) return [2, n - 2];
  if (n <= 10) return [2, n + 8];
  if (n <= 12) return [3, n - 10];
  if (n <= 18) return [3, n];
  if (n <= 36) return [4, n - 18];
  if (n <= 54) return [5, n - 36];
  if (n <= 56) return [6, n - 54];
  if (n <= 71) return [8, n - 54];
  if (n <= 86) return [6, n - 68];
  if (n <= 88) return [7, n - 86];
  if (n <= 103) return [9, n - 86];
  return [7, n - 100];
}

function periodicCat(n) {
  if ([1, 6, 7, 8, 15, 16, 34].includes(n)) return "nonmetal";
  if ([2, 10, 18, 36, 54, 86, 118].includes(n)) return "noble";
  if ([9, 17, 35, 53, 85, 117].includes(n)) return "halogen";
  if ([3, 11, 19, 37, 55, 87].includes(n)) return "alkali";
  if ([4, 12, 20, 38, 56, 88].includes(n)) return "alkaline";
  if ([5, 14, 32, 33, 51, 52].includes(n)) return "metalloid";
  if (n >= 57 && n <= 71) return "lanth";
  if (n >= 89 && n <= 103) return "actin";
  if ([13, 31, 49, 50, 81, 82, 83, 84, 113, 114, 115, 116].includes(n)) return "post";
  return "trans";
}

